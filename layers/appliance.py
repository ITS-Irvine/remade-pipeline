# Table 1 final: ZIP TO CAR
@pa.check_types
def compute_zip_to_car(   # FIXME: types
        df_long: pa.typing.DataFrame[ApplianceZipGenerationSchema],
        car_data_file: Path
        ) -> pa.typing.DataFrame[ApplianceZipToCarByApplianceAndAgeSchema]:
    """Compute ZIP-to-CAR flow mapping using nearest-neighbor routing.

    For each ZIP code in the survey data, finds the nearest CAR site
    within a 500-mile radius using :func:`compute_nearest_neighbor_mapping`,
    then joins the mapping onto the survey data to produce Table 1
    (ZIP-to-CAR flows by appliance type and age).

    Parameters
    ----------
    df_long : pa.typing.DataFrame[ApplianceZipGenerationSchema]
        Long-format survey data from :func:`read_survey_data`.

    Returns
    -------
    pa.typing.DataFrame[ApplianceZipToCarByApplianceAndAgeSchema]
        ZIP-to-CAR flows with ``zip_id``, ``car_id``, ``n1_car``,
        ``n2_car``, ``geometry_car``, and all material weight/trip
        columns aggregated by ``o_id``, ``zip_id``, ``zip_code``,
        ``appltype``, and ``age``.

    Raises
    ------
    ValueError
        If any ZIP code has no CAR mapping (null ``car_id``).
    ValueError
        If trip/weight data is inconsistent (non-zero trips with
        zero weight or vice versa for any vehicle class).

    Warns
    -----
    logger.warning
        If ZIP codes in the survey data don't match any ZCTA geometry
        (dropped when ``strict=False``).

    Notes
    -----
    - CAR data is loaded from :func:`read_car_rdrs`.
    - ZCTA representative points are used as ZIP code origins via
      :func:`get_appliance_zips`.
    - Search radius: 500 miles, max 3 candidate CARs per ZIP.
    - FIXME: ``o_id``, ``zip_id``, and ``zip_code`` are redundant
      in the groupby key.

    See Also
    --------
    compute_nearest_neighbor_mapping : Core nearest-neighbor routing.
    get_appliance_zips : ZCTA origin geometries.
    read_car_rdrs : CAR site data.
    """

    # this will read the most recent CAR data directly from 
    # DTSC's ARCGIS MAP: https://dtsc.maps.arcgis.com/apps/instant/nearby/index.html?appid=57fd38f812d4467e9768ba6974d5db8c
    # (referenced from: https://dtsc.ca.gov/certified-appliance-recycler-car-program/#CARmap)
    # url = "https://services3.arcgis.com/Oy2JTCD10wkoelxS/arcgis/rest/services/CAR_coord_240410Map/FeatureServer/0/query?f=json&maxRecordCountFactor=4&resultOffset=0&resultRecordCount=8000&where=1%3D1&orderByFields=FID&outFields=*&outSR=102100&spatialRel=esriSpatialRelIntersects"
    # car=read_car_data(url)
    # car_mon=(
    #     read_car_data_mon()
    #     .assign(
    #         car_id=lambda x: 'CAR' + x.car.astype(int).astype(str).str.zfill(5)
    #     )
    # )
    car_mon=read_car_endpoints(car_data_file=car_data_file)

    used_zips=get_appliance_zips(df_long).rename(columns={'geometry_merged':'geom_zip'})

    # map zips to CAR sites
    zip_car_mapping=(
        compute_nearest_neighbor_mapping(
            'zip_to_car',
            used_zips.add_col_suffix('_zip').reset_index().rename(columns={'id':'zip_id'}),'geometry_zip',
            car_mon.add_col_suffix('_car').reset_index().rename(columns={'id':'car_id'}),'geometry_car'
            # ,'rdrs_id'
            ,'zip_id'
            ,radius=500,max_options=3)
        .rename(
            columns={
                # 'car_id':'car',
                'business_name':'destination',
                'business_location':'destination_address'
        })
    )

    # remove flows with bad ZIPs
    bad_zips = ~df_long.zip_code.isin(used_zips.index.str.replace(r'^ZIP','',regex=True))
    strict=False
    if bad_zips.any():
        if strict:
            raise ValueError(f"Found {bad_zips.sum()} rows with bad ZIP codes:")
        else:
            logger.warning(f"Dropping {bad_zips.sum()} rows with bad ZIP codes:")
            wdisplay(df_long[bad_zips])
            df_long = df_long[~bad_zips]

    table1_zip_to_car=(
        df_long
        .assign(zip_id=lambda x: 'ZIP'+x.zip_code.astype(int).astype(str).str.zfill(5))
        .groupby(['o_id','zip_id','zip_code' # FIXME: lots of redundancy here
                  ,'appltype','age']).sum().drop(columns=['ttype'])
        .reset_index()
        .join(
            zip_car_mapping
            [['zip_id','car_id','n1_car','n2_car','geometry_car']]
            .set_index('zip_id'),on='zip_id')
    )

    # data checks    
    bad=table1_zip_to_car.car_id.isna()
    if bad.any():
        logger.error(f"{len(bad)} rows with missing CAR mapping:")
        wdisplay(table1_zip_to_car[bad])
        raise ValueError("Missing CAR mapping found; see log for details.")

    bad=(
        ~(  ((table1_zip_to_car.lda_trips>0)&((table1_zip_to_car.lda_weight>0)))
            | ((table1_zip_to_car.lda_trips==0)&(table1_zip_to_car.lda_weight==0))  )
        |
        ~(  ((table1_zip_to_car.ldt_trips>0)&((table1_zip_to_car.ldt_weight>0)))
            | ((table1_zip_to_car.ldt_trips==0)&(table1_zip_to_car.ldt_weight==0))  )
        |
        ~(  ((table1_zip_to_car.mdt_trips>0)&((table1_zip_to_car.mdt_weight>0)))
            | ((table1_zip_to_car.mdt_trips==0)&(table1_zip_to_car.mdt_weight==0))  )
        )
    if bad.any():
        logger.error(f"{len(bad)} rows with inconsistent trip/weight data:")
        wdisplay(table1_zip_to_car[bad])
        raise ValueError("Inconsistent trip/weight data found; see log for details.")

    wt_units = dict.fromkeys(['weight','ferrous','nonferrous','hazardous','other',
                              'total','lda_weight','ldt_weight','mdt_weight'], 'short_ton')
    
    table1_zip_to_car=table1_zip_to_car.assign(
        d_id=lambda x: x.car_id
        # d_id=lambda x: 'CAR' + x.car.astype(int).astype(str).str.zfill(5)
    ).pipe(assign_units, wt_units)

    return table1_zip_to_car


