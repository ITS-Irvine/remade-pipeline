# material composition estimates
def read_appliance_material_composition(
    mcfile='material_composition.csv'
    ) -> DataFrame: # FIXME: types
    """Load appliance material composition estimates from CSV.

    Reads the material composition spreadsheet, renames appliance type
    columns to short codes, transposes the matrix so appliance types
    are rows and material fractions are columns, and cleans column names.

    Parameters
    ----------
    mcfile : str, default 'material_composition.csv'
        Filename under the ``appliance_data`` directory.

    Returns
    -------
    pd.DataFrame
        Material composition matrix indexed by appliance type short code
        (``rf``, ``fz``, ``cc``, etc.), with columns for material
        fractions (``ferrous``, ``nonferrous``, ``hazardous``, ``other``,
        ``weight``).

    Notes
    -----
    - Column renaming map:

      - ``refrigerator`` → ``rf``, ``freezer`` → ``fz``,
        ``central_cooling`` → ``cc``, ``wall_cooling`` → ``ww``,
        ``evaporative_cooler`` → ``evcl``, ``water_heater`` → ``wh``,
        ``stove`` → ``st``, ``oven`` → ``ov``, ``microwave`` → ``mw``,
        ``dishwasher`` → ``dw``, ``washer`` → ``cw``, ``dryer`` → ``cd``,
        ``white_goods`` → ``wg``.

    - The transpose flips the matrix so that each row is an appliance
      type with its material composition fractions.

    See Also
    --------
    read_survey_data : Uses composition data to compute material weights.
    """
    df_mc = pd.read_csv(cpath('appliance_data',mcfile), index_col=0).clean_names()

    cols={
    'refrigerator':'rf',
    'freezer':'fz',
    'central_heater':'ch',
    'central_cooling':'cc',
    'wall_cooling':'ww',
    'evaporative_cooler':'evcl',
    'water_heater':'wh',
    'stove':'st',
    'oven':'ov',
    'microwave':'mw',
    'dishwasher':'dw',
    'washer':'cw',
    'dryer':'cd',
    'white_goods':'wg'}
    # flip the composition dataframe so we can join it. The material names are dirty so we strip them and clean them up
    df_mc2 = df_mc.rename(columns=cols).T.rename(columns=lambda x: x.strip()).clean_names()
    return(df_mc2)

