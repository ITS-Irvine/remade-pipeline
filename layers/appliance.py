# TABLE 2: CAR to shredder

def compute_car_to_shredder(   # FIXME: types
    table1_zip_to_car: pd.DataFrame,
    lf_car_flows:      pd.DataFrame,
    car_data_file:     Path
    ) -> DataFrame:
    """Compute CAR-to-shredder flows and aggregate all CAR inflows.

    Maps each CAR to the nearest shredder within 500 miles, computes
    total CAR inflows (survey + diverted white goods), and calculates
    shredder-bound weight and trips.

    Parameters
    ----------
    table1_zip_to_car : pd.DataFrame
        ZIP-to-CAR flows from :func:`compute_zip_to_car`.
    lf_car_flows : pd.DataFrame
        Landfill-to-CAR flows from :func:`compute_landfill_car_flows`.

    Returns
    -------
    tuple of (pd.DataFrame, pd.DataFrame)
        - ``table2_car_to_shred`` — CAR-to-shredder flows with
          ``car_id``, ``shred_id``, ``weight_total``, ``trips``,
          origin/destination coordinates, and geometry columns.
        - ``all_car_inflows`` — Total inflows per CAR (survey +
          diverted white goods), used by downstream tables.

    Notes
    -----
    - Total CAR inflows = survey inflows + landfill white goods.
    - ``weight_total`` = ``(total + white_goods) × 0.994`` (0.6%
      processing loss factor).
    - ``trips`` = ``weight_total / 20`` (20 tons per trip assumption).
    - Shredder entities from :func:`read_shredder_endpoints`.
    - Search radius: 500 miles, max 3 candidate shredders per CAR.
    - FIXME: Rows with null ``car_id`` are dropped — needs validation.

    See Also
    --------
    compute_nearest_neighbor_mapping : Core nearest-neighbor routing.
    read_shredder_endpoints : Shredder entity data.
    """

    # compute mapping from CAR to shredders
    # car_mon=read_car_data_mon().assign(
    #     car_id = lambda x: 'CAR' + x.car.astype(int).astype(str).str.zfill(5)
    # )
    car_mon=read_car_endpoints(car_data_file=car_data_file)


    # GET THE SHREDDER ENTITIES
    # For now we pull the specific shredders from mon's list
    # FIXME: but we really just need the raw dataset
    shred_ent = read_shredder_endpoints()


    car_shred_mapping=compute_nearest_neighbor_mapping(
        'car_to_shred'
        ,car_mon.add_col_suffix('_car').reset_index().rename(columns={'id':'car_id'}),'geometry_car'
        ,shred_ent.add_col_suffix('_shred').reset_index().rename(columns={'id':'shred_id'}), 'geometry_shred'
        ,'car_id',radius=500,max_options=3)

    # add on white_goods from landfill1 to CAR
    all_car_inflows=(
        # take total CAR inflows from survey
        table1_zip_to_car
        .filt(lambda x: ~x.car_id.isna())  # FIXME: DROPPING ROWS WITH NA CARS---NEED CHECK

        # total by car
        .groupby(['car_id']).sum(numeric_only=True).reset_index()

        # join on white goods from landfill1
        .join(lf_car_flows.groupby('car_id')[['white_goods']].sum(),on='car_id',how='outer').fillna(0)
    )
    
    pf = ureg('1/(20 tons)')


    table2_car_to_shred=(
        all_car_inflows

        # join the car_to_shredder_mapping
        .join(car_shred_mapping.set_index('car_id'),on='car_id',rsuffix='_csm')

        # compute the weights
        .assign(
            origin_x=lambda x: x.geometry_car.apply(lambda point: round(point.x,8)),
            origin_y=lambda x: x.geometry_car.apply(lambda point: round(point.y,8)),
            destination_x=lambda x: x.geometry_shred.apply(lambda point: round(point.x,8)),
            destination_y=lambda x: x.geometry_shred.apply(lambda point: round(point.y,8)),
            weight_total=lambda x:(
                x.total+x.white_goods.fillna(0))*0.994, # FIXME: total should be _u
            trips=lambda x: (x.weight_total * pf).pint.magnitude
        )
    )
    return table2_car_to_shred, all_car_inflows


