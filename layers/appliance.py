# Raw survey data 
@pa.check_types
def read_rass_survey_data(
        rass_data_file: Path,
        df_mc2: pa.typing.DataFrame[ApplianceMaterialCompositionSchema]
        ) -> pa.typing.DataFrame[ApplianceZipGenerationSchema]:
    """Load and process raw appliance survey data into long format.

    Reads the cleaned survey CSV, expands appliance-specific discard
    and age data into a long format, joins material composition
    fractions, and computes material weights and trip estimates by
    vehicle class.

    Parameters
    ----------
    df_mc2 : pa.typing.DataFrame[ApplianceMaterialCompositionSchema]
        Material composition matrix from
        :func:`read_appliance_material_composition`.

    Returns
    -------
    pa.typing.DataFrame[ApplianceZipGenerationSchema]
        Long-format survey data with ``zip_code``, ``appltype``,
        ``age``, ``weight``, ``ferrous``, ``nonferrous``, ``hazardous``,
        ``other``, ``lda_trips``, ``ldt_trips``, ``mdt_trips``,
        ``lda_weight``, ``ldt_weight``, ``mdt_weight``, ``o_id``, and
        ``ttype`` columns.

    Notes
    -----
    - Appliance types with ``discrd`` columns (``rf``, ``fz``) are
      processed by :func:`expand_by_discrd`; all others by
      :func:`expand_by_age`.
    - Material weights are computed as ``weight × fraction`` for each
      component (ferrous, nonferrous, hazardous, other).
    - An assertion verifies ``weight.sum() ≈ total.sum()``.
    - **OVERRIDE**: All appliance collection is assumed to be via MDT
      (medium-duty trucks) at 1,200 lbs/trip. LDA and LDT trips/weights
      are set to 0 (empty ``isin([])`` conditions).
    - ZIP codes are zero-padded to 5 digits and prefixed with ``ZIP``
      to create ``o_id`` values.

    See Also
    --------
    expand_by_discrd : Expand appliances with discard counts.
    expand_by_age : Expand appliances with age-only data.
    read_appliance_material_composition : Material composition source.
    """
    dfr = pd.read_csv(rass_data_file, low_memory=False).clean_names()
    dfr = dfr[['servzip','rfdiscrd','drfage','fzdiscrd','dfzage','dchage','dccage','dwwage','devclage',
            'dwhage','dstage','dovage','dmwage','ddwage','dcwage','dcdage','wt']]
    dfr['wt'] = dfr['wt'].replace(',', '')
    dfr['wt'] = pd.to_numeric(dfr['wt'])

    import re
    all_types=[re.sub(r'd(.*)age',r'\1',col) for col in dfr.columns if re.match(r'.*age$',col)]
    mdt_payload_factor_lbs_to_trips = 1200 # see writeup, assumed average of 1200 lbs per trip
    df_long=(
        pd.concat(
            # read data for appliances that have discrd column
            [expand_by_discrd(dfr,at) for at in ['rf','fz']]

            # read data for appliances that don't have discrd column
            +[expand_by_age(dfr, at) for at in list(set(all_types)-set(['rf','fz']))]
        )
        # .filt(lambda x: x.age1>0)
        .join(df_mc2,on='appltype')
        .assign(
            weight     = lambda x: x.disp   * x.weight * lb_to_tonne,      # total weight
            ferrous    = lambda x: x.weight * x.ferrous,                   # material weights...
            nonferrous = lambda x: x.weight * x.nonferrous,
            hazardous  = lambda x: x.weight * x.hazardous,
            other      = lambda x: x.weight * x.other,
            total      = lambda x: x.ferrous + x.nonferrous + x.hazardous + x.other, # for checks

            # assume one trip per appliance; LDT for everything except evcl and mw
            # default=np.nan used to force as floats
            # OVERRIDE: old approach used 1:1 disp to trips.
            lda_trips  = lambda x: case_when( x.appltype.isin([]), x.disp,    # car (LDA) if evcl or mw # OVERRIDE all mdt
                                            True, 0.0, default=np.nan),       # light-duty truck otherwise (so no trips)
            lda_weight = lambda x: case_when( x.appltype.isin([]), x.weight,  # car (LDA) if evcl or mw # OVERRIDE all mdt
                                            True, 0.0, default=np.nan),       # light-duty truck otherwise (so no weight)
            ldt_trips  = lambda x: case_when( x.appltype.isin([]), x.disp,    # light-duty truck if not evcl or mw # OVERRIDE all mdt
                                            True, 0.0, default=np.nan),       # car (LDA) otherwise (so not trips)
            ldt_weight = lambda x: case_when( x.appltype.isin([]), x.weight,  # car (LDA) if evcl or mw # OVERRIDE all mdt
                                            True, 0.0, default=np.nan),       # light-duty truck otherwise (so no weight)
            
            # OVERRIDE: new approach is to assume collection of all appliances is via mdt and aggregated, 
            # 
            mdt_weight = lambda x: case_when( ~x.appltype.isin([]), x.weight, # OVERRIDE all mdt
                                            True, 0.0, default=np.nan),       # OVERRIDE all mdt
            mdt_trips  = lambda x: case_when( ~x.appltype.isin([]), x.weight * ureg('tonne').to('lbs') / mdt_payload_factor_lbs_to_trips,    # OVERRIDE all mdt
                                            True, 0.0, default=np.nan),       # OVERRIDE all mdt

        )
        .rename(columns={'servzip':'zip_code'})
        .assign(
            zip_code = lambda x: x.zip_code.astype(int).astype(str).str.zfill(5),
            o_id = lambda x: 'ZIP' + x.zip_code
            )
    )
    return df_long


