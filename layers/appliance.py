@pa.check_types
def load_appliance_flows(
    case_a,
    caports_ent: DataFrame[EndpointSchema],     # port mappings for appliance exports
    matmap,
    data_source='processed_data_appliance',
    refr_case='min', # min or max
    year=2021,
    layer='Appliances'
) -> DataFrame[ApplFlowSchema]:
    #%%

    # Read in appliance flows, from the six distinct model tables
    logger.info("Reading Appliance Flows")

    appliance_metals_dir=f'./{case_a}/'
    
    # FIXME: should provide an option to regenerate the appliance flow files from raw data (re-run the model)
    # FIXME: some of these outputs are read from processed_data_appliance, some from output_appliance; need to standardize

    # if re.match(r'.*processed-inputs',cpath(data_source,f'{appliance_metals_dir}OD_Appliances_Metals_table1.csv')):
    #     logger.warning("It looks like you're reading directly from the processed-inputs directory. This will bypass any manual corrections or updates made to the processed_data_appliance files. If this is intentional, you can ignore this warning. Otherwise, you may want to update the data_source path to point to the processed_data_appliance directory to ensure you're using the most up-to-date and corrected data.")
    #     appflw_s=load_appliance_flows_mon(case_a, caports_ent, matmap, data_source, refr_case, year, layer)
    # else:
    logger.info("Reading from processed_data_appliance, skipping the original flow processing logic. If you want to re-run the original flow processing logic, set data_source to point to the processed-inputs directory.")
    appflw_s=load_appliance_flows_model(case_a, caports_ent, matmap, data_source, refr_case, year, layer)


    logger.info("Transforming Appliance Flows into long format")

    # now let's grab the distinct weight flows and trips and convert the frame into long format
    ttypes=['lda','ldt','mdt','shredder','haz','nonferrous','ferrous','other','white_goods','refr']
    dropcols=flatten_lists([[x+'_trips',x+'_weight'] for x in ttypes])
    appflow_long = (
        pd.concat([
            appflw_s
            .filt(lambda x: x[flowtype+'_trips'].notna() ) # only keep rows where flowtype_trips has a value (even if 0<-FIXME: a restriction related to downstream endpoint reconcilliation)
            .assign(
                mattype=flowtype,
                trips=lambda x: x[flowtype+'_trips'],
                wt_sent=lambda x: x[flowtype+'_weight'].astype('pint[short_ton]')
            )
            .filt(lambda x: x.trips>0)
            .assign(
                pf=lambda x: x.wt_sent/x.trips
            )
            .drop(columns=dropcols)
            for flowtype in ttypes
        ], ignore_index=True)

        # now we need to properly distinguish between trip types/flows and vehicle classes
        # upstream, appliance deliveries are already split between LDA and LDT and mdt. We will define those
        # material types as 'white_goods' and set their EMFAC vehicle classes to LDA and LDT2 and T7 accordingly.
        # all other mattypes actually specify the material types and we assume they will be T7s
        .assign(
            vehclass=lambda x: (
                # all non-LDA/LDT/mdt will be class 8 trucks
                np.where(~x.mattype.str.match('^(lda|ldt|mdt)$'),'T7 Tractor Class 8',x.mattype)
            )
        )
        .assign(
            # by default export uses POLA drayage trucks
            vehclass=lambda x: x.vehclass.mask(x.ttype.str.match('.*to_export'),'T7 POLA Class 8')
        )
        .assign(
            # If the port is OAKLAND, it uses POAK drayage trucks
            vehclass=lambda x: (
                x.vehclass.mask(x.ttype.str.match('.*to_export')&x.destination.fillna('').str.upper().str.match('.*OAKLAND'),'T7 POAK Class 8')
            )
        )
        .assign(
            vehclass=lambda x: x.vehclass
                .str.replace('lda','LDA')
                .str.replace('ldt','LDT2') # LDT can be LDT1 or LDT2 in EMFAC, we choose the larger here as an emmissions upper bound
                .str.replace('mdt','T6 Instate Delivery Class 5') # see writeup
            ,
            mattype=lambda x: np.where(x.mattype.str.match('^(lda|ldt|mdt)$'),'white_goods',x.mattype),
        )
    )

    logger.info("Mapping appliance flow material and vehicle classes")

    appflw_s=(appflow_long
        # map trip type to EMFAC class
        .assign(
            EMFAC_class=lambda x: x.vehclass,
            material_stream='Appliances',
            MAT_class=lambda x: x.apply(lambda y: trip_type_mat_class_map[y.mattype],axis=1),
        )
        .join(
            pd.concat([
                matmap
                # add HAZ to material mappings
                ,pd.DataFrame(
                    {'material_category':['HAZ'],'material_subcategory':['HAZ'],'material_type':['HAZ'],'grouping4':['HAZ']
                     ,'include':[True]})
                ]
                ,ignore_index=True)
            .assign(idx=lambda x: x.material_category+':'+x.material_subcategory+':'+x.material_type).set_index('idx')[['grouping4']]
            ,on='MAT_class')
        # .assign(
        #     car=lambda x: x.car.fillna(0).astype(int)
        # )
        # split the MAT_class into its components
        .pipe(
            lambda df: df.assign(
                **df.MAT_class.str.split(':',expand=True).rename(
                    columns={0:'material_category',1:'material_subcategory',2:'material_type'}
                )))
        .assign(
            material_type=lambda x: x.material_type.mask(x.refr.notna(),x.refr)
        )
        
        .rename(columns={'grouping4':'material_grouping'})
        .add_column_if_missing('year',year)
        .add_column_if_missing('layer',layer)
    )
    
    # # FIXME: this is a lot of slop to support panderas checking:
    
    # normalize ship_containers_int -> scalar numeric, force non-HAZ -> NA, convert to nullable Int
    # def _unwrap_numeric(x):
    #     # defensive unwrapping in case a nested object slipped in
    #     if isinstance(x, pd.Series):
    #         return x.iloc[0] if len(x) else pd.NA
    #     if isinstance(x, pd.DataFrame):
    #         return x.to_numpy().ravel()[0] if x.size else pd.NA
    #     if isinstance(x, (list, tuple, np.ndarray)):
    #         return x[0] if len(x) else pd.NA
    #     return x

    # appflw_s = (
    #     appflw_s
    #     .assign(ship_containers_int=lambda df: df['ship_containers_int'].apply(_unwrap_numeric))
    # )
    # appflw_s['ship_containers_int'] = pd.to_numeric(appflw_s['ship_containers_int'], errors='coerce')
    # # only keep container counts for HAZ rows; other groupings allowed to be missing
    # appflw_s.loc[appflw_s['material_grouping'] != 'HAZ', 'ship_containers_int'] = pd.NA
    # appflw_s['ship_containers_int'] = appflw_s['ship_containers_int'].astype('Int64')
    appflw_s['ship_containers_int'] = appflw_s['ship_containers_int'].fillna(-1) # flag as bad

    # log any HAZ rows that ended up missing/invalid after coercion
    bad_haz = (
        appflw_s['material_grouping'].eq('HAZ') 
        & appflw_s['ship_containers_int']<0
        & (appflw_s['ttype']=='car_to_reclaimer')
    )
    if bad_haz.any():
        logger.error("HAZ rows with missing/invalid ship_containers_int: %s", bad_haz.sum())
        logger.error(appflw_s.loc[bad_haz, ['o_id','d_id','mattype','ship_containers_int']].head(10).to_string())
        
    # FIXME: we still have duplicates on the ApplFlowIdSchema; need to investigate further upstream
    # for now, we'll just aggregate them here
    from utils.pandera_checks import get_required_columns
    from core.model_types import ApplFlowIdSchema
    to_agg=set([k for k,v in ApplFlowSchema.to_schema().columns.items()]) - set(get_required_columns(ApplFlowIdSchema))
    appflw_sa = (
        appflw_s
        
        # FIXME: the following are for backwards compatibility with the original flow processing code, 
        # which had some columns that were not always present. We should investigate further upstream to 
        # understand why those columns are missing and whether we can ensure they are always present 
        # in the source data.
        # the main issue is that dest_x and dest_y are later used to determine CAR and reclaimer RDRS geocodes
        .add_column_if_missing('orig_x',None)
        .add_column_if_missing('orig_y',None)
        .add_column_if_missing('destination',None)
        .add_column_if_missing('destination_address',None)
        .add_column_if_missing('car',None)
        # FIXME: have to temporarily set container type to string to aggregate properly
        # maybe should always explicitly representing the shipping container type
        .assign(
            container_type=lambda x: x.container_type.fillna('40ft shipping').astype(str),
            
            # BACKFILL CAR
            car=lambda x: x.car.fillna(
                x.car_id.str.extract(r'CAR(\d+)').iloc[:,0]  # extract car number from d_id if it matches the pattern
            ).fillna(-1).astype(int)  # flag missing cars as -1 for now; we can investigate further upstream
        )
        .groupby(get_required_columns(ApplFlowIdSchema)).agg({
            # take the first value of the orig/dest coordinates
            **dict.fromkeys([k for k in to_agg if re.match(r'(orig|dest)_[xy]|^destination.*|^car$',k)], 'first'),
            # sum all other required columns
            **dict.fromkeys([k for k in to_agg if not re.match(r'(orig|dest)_[xy]|^destination.*|^car$',k)], 'sum'),
        })
        .reset_index()
    )   
    
    return(appflw_sa)


@pa.check_types
def get_appliance_zips(
    appflw_a: DataFrame[ApplianceZipGenerationSchema]
) -> DataFrame[LayerEndpointSchema]:
    logger.info("Reading Zip Code tabulation areas")

    # zcta=gpd.read_file(cpath('gis_data','tl_2020_us_zcta520.zip')).clean_names()              # national is really big
    zcta=gpd.read_file(cpath('gis_data','CA_ZCTA_2020-fixed.zip')).clean_names()  # ...so we use california: https://hub.arcgis.com/datasets/CalEMA::census-2020-california-zip5-postal-code-areas/explore


    # Since the ZCTAs are imperfect, we also read in the ZCTA to county mapping.
    # It's unclear whether this is purely geographic or if its based upon the
    # specific mail routes that zip codes actually denote.  
    # FIXME: consider using this method elsewhere since we did a nearest spatial
    # join in other places  
    zcta_cty=(
        pd.read_csv(cpath('gis_data','tab20_zcta520_county20_natl.txt'),delimiter='|',
                    dtype={'GEOID_COUNTY_20':str,
                        'GEOID_ZCTA5_20':str})
        .clean_names()
    )


    # Now we select all origin zip codes in the appliance data, attach the
    # corresponding ZCTA geometry to extract its centroid for use as the source
    # point, and county mapping. We then convert it into the standard entity
    # format we defined above for RDRS locations.

    logger.info("Creating ZCTA entities")

    zorig_s=(
        appflw_a
        # the following will have zip code origins
        .filt(lambda x: x.ttype.isin(['appliance_collection']))
        .groupby('o_id').first().reset_index() # get set of unique zip codes
        .assign(
#            rdrs_id=lambda x: x.apply(lambda row: f"ZIP{row.zip_code}",axis=1)
            zip_code=lambda x: x.o_id.str.replace('ZIP','')
        )
        # .drop(columns='index')
        .join(
            # use a groupby-first just to make sure we have a unique mapping
            zcta.groupby('zcta5ce20').first()
            .set_crs(zcta.crs) # grouping messes with the crs, so we reset it
            ,on='zip_code'
        )
        .set_geometry('geometry')
        .assign(
            geometry_pt=lambda x: x.geometry.to_crs(crs_ca).representative_point().to_crs(crs_ll)
        )
        .join(
            # geoid_zcta5_20 is not a unique key due to geometries crossing counties and such. 
            # we sort by area descending and take the first (largest)
            zcta_cty
            .sort_values(['geoid_zcta5_20','arealand_zcta5_20'],ascending=[True,False])
            .groupby('geoid_zcta5_20').first()[['geoid_county_20','namelsad_county_20']],
            on='zip_code'
        )
        .assign(
            id=lambda x: x.apply(lambda row: f'ZIP{row.zip_code}',axis=1),
            n1=lambda x: x.apply(lambda row: f'ZIP{row.zip_code}',axis=1),
            n2='California',
            facility_type='ZCTA',
            facility_flags='',
            county=lambda x: x.namelsad_county_20.str.replace(r'\s+County','',regex=True),
            state='California',       # Is this actually correct?
            country='United States',
            # gcnt=lambda x: x.dest_x,
            src='APPLIANCE ORIG',
            geo_status='SUCCESS',
            geometry=lambda x: x.geometry_pt,
            geometry_agg=lambda x: x.geometry,
            geometry_src='ZCTA',
            aggregation=EndpointAggregation.ZCTA.value
        )
        # [['id','n1','n2','county','state','country'
        # #   ,'gcnt'
        #   ,'src','geo_status','geometry','aggregation','geometry_src']]
        .set_flags(allows_duplicate_labels=False)
        .set_index('id')
        [schema_to_cols(LayerEndpointSchema)]
    )
    
    is_bad_geo = zorig_s['geometry'].is_empty | zorig_s['geometry'].isna()
    strict=False
    if is_bad_geo.any():
        logger.warning("Some appliance origin ZCTAs have bad geometry: %s", is_bad_geo.sum())
        logger.warning(zorig_s.loc[is_bad_geo].head(10).to_string())
        if strict:
            raise ValueError("Bad geometries found in appliance origin ZCTAs")
        else:
            logger.warning("Removing bad geometries from appliance origin ZCTAs")
            zorig_s = zorig_s.loc[~is_bad_geo]
    
    return(zorig_s)

