# for appliances that have a discard column...
def expand_by_discrd(df,at):
    """Expand survey data for appliance types with a ``discrd`` (discard) column.

    Filters for appliances with nonzero discards, scales by the survey
    weight (``wt``), and creates three age-bin columns (``age1``,
    ``age2``, ``age3``) indicating whether each appliance belongs to
    that age group.

    Parameters
    ----------
    df : pd.DataFrame
        Raw survey data with ``{at}discrd`` and ``d{at}age`` columns.
    at : str
        Appliance type short code (e.g., ``'rf'``, ``'fz'``).

    Returns
    -------
    pd.DataFrame
        Expanded rows with ``servzip``, ``appltype``, ``discrd``,
        ``disp``, ``age``, ``age1``, ``age2``, ``age3`` columns.

    Notes
    -----
    - ``disp`` = ``discrd × wt`` (population-weighted discards).
    - Age bins: ``age{i}`` = ``wt × (age == i)`` for ``i`` in 1–3.
    - The ``ages`` list column is expanded into separate ``age1``,
      ``age2``, ``age3`` columns via DataFrame join.

    See Also
    --------
    expand_by_age : For appliance types without a ``discrd`` column.
    read_survey_data : Calls both expand functions.
    """
    discrd_key=at+'discrd'
    age_key='d'+at+'age'
    ret= (
        # filter for items that have nonzero discards
        df.filt(lambda x: x[discrd_key]>0)
        .assign(
            appltype=at,                           # set the appliance type
            disp=lambda x: x[discrd_key] * x.wt,   # scale by pop weight
            # create the age values: 3 values = {0,1} if it belongs to age[123] or not
            ages=lambda x: x.apply(lambda row: [row.wt*(row[age_key]==(i+1)) for i in range(3)],axis=1)
            )
        .rename(columns={discrd_key:'discrd',
                         age_key:'age'})
        [['servzip','appltype','discrd','disp','age','ages']]
    )

    # Expand the 'ages' column into separate columns
    ret = (
        ret.join(pd.DataFrame(ret['ages'].tolist(),
                              index=ret.index,
                              columns=[f'age{(i+1)}' for i in range(3)]))
        .drop(columns='ages')
    )
    return ret


# for appliances that only have an age column
def expand_by_age(df,at):
    """Expand survey data for appliance types with only an ``age`` column.

    Filters for appliances with age values < 4 (valid age bins),
    sets ``disp = wt`` (no discard scaling), and creates three age-bin
    columns.

    Parameters
    ----------
    df : pd.DataFrame
        Raw survey data with ``d{at}age`` column.
    at : str
        Appliance type short code (e.g., ``'cc'``, ``'ww'``).

    Returns
    -------
    pd.DataFrame
        Expanded rows with ``servzip``, ``wt``, ``appltype``, ``disp``,
        ``age``, ``age1``, ``age2``, ``age3`` columns.

    Notes
    -----
    - Unlike :func:`expand_by_discrd`, ``disp`` is simply ``wt``
      (no discard count to scale by).
    - Age bins: ``age{i}`` = ``wt × (age == i)`` for ``i`` in 1–3.

    See Also
    --------
    expand_by_discrd : For appliance types with a ``discrd`` column.
    read_survey_data : Calls both expand functions.
    """
    age_key='d'+at+'age'
    ret= (
        # filter for items that have nonzero discards
        df.filt(lambda x: x[age_key]<4)
        .assign(
            appltype=at,                     # set the appliance type
            disp=lambda x: x.wt,             # scale by pop weight
            # create the age values: 3 values = {0,1} if it belongs to age[123] or not
            ages=lambda x: x.apply(lambda row: [row.wt*(row[age_key]==(i+1)) for i in range(3)],axis=1)
            )
        .rename(columns={age_key:'age'})
        [['servzip','wt','appltype','disp','age','ages']]
    )

    # Expand the 'ages' column into separate columns
    ret = (
        ret.join(pd.DataFrame(ret['ages'].tolist(),
                              index=ret.index,
                              columns=[f'age{(i+1)}' for i in range(3)]))
        .drop(columns='ages')
    )
    return ret


