def compute_shred_to_landfillctmsr( # FIXME: types
        all_shred_inflows: pd.DataFrame,
        df_mc2: pd.DataFrame
        ) -> pd.DataFrame:
    """Compute shredder-to-CTMSR-landfill flows for processing residuals.

    Maps each shredder to the nearest CTMSR landfill within 500 miles
    and computes residual ("other") waste tonnage and trips.

    Parameters
    ----------
    all_shred_inflows : pd.DataFrame
        Total inflows per shredder from :func:`compute_shredder_to_port`.
    df_mc2 : pd.DataFrame
        Material composition matrix for white goods residual fraction.

    Returns
    -------
    pd.DataFrame
        Shredder-to-landfill flows with ``shred_id``, ``lfc_id``,
        ``other_weight``, ``other_trips``, ``landfill_ctmsr``, and
        geometry columns.

    Notes
    -----
    - ``other_weight`` = ``other + white_goods × wg.other``.
    - ``other_trips`` = ``other_weight / 20``.
    - Search radius: 500 miles, max 3 candidate landfills per shredder.
    - FIXME: ``rsuffix='_lfcx'`` is used to avoid column name conflicts
      — should be handled explicitly.

    See Also
    --------
    read_ctmsr_landfill_endpoints : CTMSR landfill entity data.
    compute_nearest_neighbor_mapping : Core nearest-neighbor routing.
    """

    landfills_ctmsr=read_ctmsr_landfill_endpoints()

    shred_lfc_mapping=compute_nearest_neighbor_mapping(
        'shred_to_landfill_ctmsr'
        ,all_shred_inflows[['shred_id','geometry_shred']]
        # .rename(columns={'index_right':'index_right_old'})    # can't have index_right here because we do a spatial join later
        .to_crs(crs_ll),'geometry_shred',
        landfills_ctmsr.add_col_suffix('_lfc').reset_index().rename(columns={'id':'lfc_id'}),'geometry_lfc',
        'shred_id',radius=500,max_options=3)

    map_join_key='shred_id'
    
    pf = ureg('1/(20 tons)')

    table3b_shred_landfillctmsr =(
        all_shred_inflows.drop(columns=['geometry_shred', 'distance'])
        .join(shred_lfc_mapping.set_index(map_join_key),
              on=map_join_key
              ,rsuffix='_lfcx' # FIXME: to avoid conflicts, but should deal with this explicitly
              )
        .assign(
            other_weight=lambda x: x.other + x.white_goods * df_mc2.loc['wg','other'],
            other_trips =lambda x: (x.other_weight * pf).pint.magnitude,
        )
    )
    return table3b_shred_landfillctmsr


