def compute_fluid_diversion( # FIXME: types
        table1_zip_to_car_by_appliance_and_age: DataFrame[ApplianceZipToCarByApplianceAndAgeSchema],
        case:                                   str,
        refr_recovery_file:                     Path,
        refr_gwp_file:                          Path,
        refr_containers_file:                   Path,
        refr_vehcap_file:                       Path
        ) -> pd.DataFrame: # FIXME: return type
    """Compute refrigerant fluid diversion from CARs to reclaimers.

    Calculates recovered refrigerant quantities by appliance type and
    age at each CAR, determines shipping container requirements and
    vehicle trips for transport to reclaimers, and produces min/max
    case estimates for refrigerant shipping.

    Parameters
    ----------
    table1_zip_to_car_by_appliance_and_age : pa.typing.DataFrame[ApplianceZipToCarByApplianceAndAgeSchema]
        ZIP-to-CAR flows by appliance type and age from
        :func:`compute_zip_to_car`.
    case : str
        Case label for output file naming.

    Returns
    -------
    pd.DataFrame
        Shipped refrigerant records with ``car_id``, ``appltype``,
        ``age``, ``refr``, ``rec_kg``, ``ship_containers_int``,
        ``ship_weight_kg``, ``emfac_class``, ``trips``, ``case``
        (``'min'`` or ``'max'``), and container/vehicle metadata.

    Notes
    -----
    - **Recovery rates**: Loaded from ``appliance-refrigerants - recovery.csv``,
      joined on appliance type and age.
    - **Global warming potentials**: From ``appliance-refrigerants - gwp.csv``,
      used to compute CO2-equivalent emissions.
    - **Container specifications**: From
      ``appliance-refrigerants - refrigerant_containers.csv``. Container
      capacity = 80% of water capacity × specific gravity (fill limit).
    - **Vehicle capacities**: From
      ``appliance-refrigerants - vehicle_capacity.csv``. Trips =
      ``ceil(containers) / vehicle_capacity``.
    - **Min/max case**: When multiple container sizes are feasible for
      a given CAR/appliance/age/refrigerant group, the lightest
      container is labeled ``'min'`` and the heaviest ``'max'``.
      Only the first and last container options are kept.
    - Intermediate recovery estimates are saved to
      ``output_appliance/{case}/OD_Appliances_Metals_t4_refrigerant_recovery_estimates.csv``.

    See Also
    --------
    compute_car_to_reclaimer_mapping : Maps CARs to nearest reclaimers.
    run_appliance_flow_model : Calls this function and joins results
        with reclaimer mapping.
    """
    logger.info("Computing diverted refrigerant fluids...")

    # read recovery rates
    refr_recov = pd.read_csv(refr_recovery_file).clean_names()

    # read global warming potentials and container/vehicle data
    refr_gwp   = pd.read_csv(refr_gwp_file).clean_names()

    # read refrigerant container specifications
    refr_cont  = (
        pd.read_csv(refr_containers_file)
        .clean_names()
        .set_index('model_size')
        .transpose()
        .reset_index()
        .filt(lambda x: x['index'].str.match(r'.*_lbs'))
        .rename(columns={'index': 'model_size'})
        .clean_names()
        .assign(
            water_capacity_lb_=lambda x: x.water_capacity_lb_.astype(float),
            nominal_tare_weight_lb_=lambda x: x.nominal_tare_weight_lb_.astype(float),
        )
    )

    # read vehicle containment capacities    
    refr_veh = (
        pd.read_csv(refr_vehcap_file).clean_names()
        .pipe(lambda df:(
            df.melt(
                id_vars=[col for col in df.columns if '_lbs' not in col],
                value_vars=[col for col in df.columns if '_lbs' in col],
                var_name='model_size',
                value_name='capacity'
            )
        ))
    )

    # recovered refrigerant by appliance type and age at each car
    car_refr_recov = (
        table1_zip_to_car_by_appliance_and_age
        .join(refr_recov.reset_index().set_index(['appl', 'age']), on=['appltype', 'age'])
        .filt(lambda x: ~x.refr.isna())
        .assign(rec_kg=lambda x: x.disp * x.rec_unit_kg_)
        .groupby(['car_id', 'appltype', 'age', 'refr', 'rec_unit_kg_'])
        .agg({'disp': 'sum', 'rec_kg': 'sum'})
    )

    # compute total recovered fluids by appliance type, age, and refrigerant type
    car_refr_recov_comp = (
        car_refr_recov
        .groupby(['appltype', 'age', 'refr', 'rec_unit_kg_'])
        .agg({'disp': 'sum', 'rec_kg': 'sum'})
        .reset_index()
        .join(refr_gwp.set_index('refr'), on='refr')
        .assign(
            co2_eq=lambda x: x.rec_kg * x.gwp * kg_to_tonne / 1000,
        )
    )
    car_refr_recov_comp.to_csv(cpath('output_appliance', f'{case}/OD_Appliances_Metals_t4_refrigerant_recovery_estimates.csv'))


    # the recovered fluids are now the origins for shipping to reclaimers
    shipped = (
        car_refr_recov
        .reset_index()
        .groupby(['car_id', 'appltype', 'age', 'refr', 'rec_unit_kg_'])
        .agg({'rec_kg': 'sum'})
        .reset_index()
        .join(refr_gwp.set_index('refr'), on='refr')
        .join(refr_cont[['model_size', 'water_capacity_lb_', 'nominal_tare_weight_lb_', 'standard_specification']], how='cross')
        .assign(
            cont_cap_kg           = lambda x: 0.8 * x.water_capacity_lb_ * x.spec_grav * lb_to_kg,
            ship_containers       = lambda x: x.rec_kg / x.cont_cap_kg,
            ship_containers_int   = lambda x: np.ceil(x.ship_containers),
            ship_container_weight = lambda x: x.nominal_tare_weight_lb_ * lb_to_kg * x.ship_containers_int,
            ship_refr_wt_full     = lambda x: np.floor(x.ship_containers) * x.cont_cap_kg,
            ship_refr_wt_partial  = lambda x: x.rec_kg - np.floor(x.ship_containers) * x.cont_cap_kg,
            ship_weight_kg        = lambda x: (
                x.ship_container_weight
                + x.ship_refr_wt_full
                + x.ship_refr_wt_partial
            ),
        )
        .join(refr_veh[['emfac_class', 'model_size', 'capacity']].set_index('model_size'), on='model_size')
        .assign(
            trips=lambda x: x.ship_containers_int / x.capacity
        )
    )

    shipped_case = (
        shipped
        .sort_values(['car_id', 'appltype', 'age', 'refr', 'ship_weight_kg'], ascending=[True, True, True, True, True])
        .assign(
            cnt=lambda x: x.groupby(['car_id', 'appltype', 'age', 'refr']).ship_weight_kg.transform('count'),
            ord=lambda x: x.groupby(['car_id', 'appltype', 'age', 'refr']).ship_weight_kg.transform('cumcount'),
            case=lambda x: case_when(
                x.ord == 0, 'min',
                x.ord > 0, 'max',
                True, 'other'
            )
        )
        .filt(lambda x: (x.ord == 0) | (x.ord == (x.cnt - 1)))
    )

    return shipped_case


def compute_diverted_appliances(model_year: int = 2021) -> DataFrame[RawRDRSData]:
    """Load RDRS flow data for white goods diverted through landfills.

    Filters RDRS flow data for 2021 records where the material
    category matches White Goods and the focal entity or organization
    is a landfill.

    Returns
    -------
    pa.typing.DataFrame[RawRDRSData]
        Diverted white goods flow records from RDRS.

    Notes
    -----
    - Filter criteria:

      - ``material_category`` matches ``'.*White Goods'``
      - ``focal_entity`` or ``focal_org`` matches ``'.*Landfill'``
      - ``year_quarter`` matches ``'2021'``

    - FIXME: Year filter is hardcoded to 2021.

    See Also
    --------
    load_rdrs_flow : RDRS flow data loader.
    compute_landfill_car_flows : Uses this data for landfill-to-CAR flows.
    """
    rdrs_flowx=load_rdrs_flow(model_year=None)
    diverted_apps=(rdrs_flowx.filt(
            lambda x:
            True
            & x.material_category.str.match(".*White Goods")
            & (x.focal_entity.str.match('.*Landfill')|x.focal_org.str.match('.*Landfill'))
            & x.year_quarter.str.match(str(model_year))
        )
    )
    return diverted_apps