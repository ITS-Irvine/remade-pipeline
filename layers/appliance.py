def compute_shredder_to_port( # FIXME: types
        table2_car_to_shred: pd.DataFrame,
        df_mc2: pd.DataFrame,
        export_destinations:DataFrame[ExportDestinationProportions]|None=None
        ) -> pd.DataFrame: # FIXME: enforce types
    """Compute shredder-to-export-port flows for ferrous and nonferrous metal.

    Aggregates shredder inflows, maps each shredder to the nearest
    California port within 500 miles, and computes ferrous/nonferrous
    export weights and trips.

    Parameters
    ----------
    table2_car_to_shred : pd.DataFrame
        CAR-to-shredder flows from :func:`compute_car_to_shredder`.
    df_mc2 : pd.DataFrame
        Material composition matrix for white goods metal fractions.

    Returns
    -------
    tuple of (pd.DataFrame, pd.DataFrame)
        - ``table3_shred_port`` — Shredder-to-port flows with
          ``shred_id``, ``port``, ``ferrous_weight``, ``ferrous_trips``,
          ``nonferrous_weight``, ``nonferrous_trips``, and geometry columns.
        - ``all_shred_inflows`` — Total inflows per shredder (used by
          Table 3b).

    Notes
    -----
    - POLA and POLB are co-located; Los Angeles is dropped to avoid
      duplication, keeping only Long Beach.
    - ``ferrous_weight`` = ``ferrous + white_goods × wg.ferrous``.
    - ``nonferrous_weight`` = ``nonferrous + white_goods × wg.nonferrous``.
    - Trips = weight / 20 (20 tons per trip).
    - Search radius: 500 miles, max 3 candidate ports per shredder.

    See Also
    --------
    get_port_endpoints : California port entity data.
    compute_nearest_neighbor_mapping : Core nearest-neighbor routing.
    """

    all_shred_inflows=(
        gpd.GeoDataFrame(
            table2_car_to_shred
            .groupby(['shred_id','n1_shred','geometry_shred']).sum(numeric_only=True).reset_index()
            # [['rdrsid','shredder','ferrous','nonferrous','trips','geometry_shred']]
            ,geometry='geometry_shred'
            ,crs=crs_ll)
        .drop(columns=['index','index_right'])
    )

    caports_ent = get_ca_port_endpoints()
    caports_use=(
        caports_ent.filt(lambda x: ~(x.n1=='LOS ANGELES'))   # since POLA and POLB are basically co-located, we'll just use POLB, so we drop LA here
        # .rename(columns={'geometry_merged':'geometry_port'})
        .add_col_suffix('_port')
        .set_geometry('geometry_port').to_crs(crs_ll)
        .reset_index()
        .rename(columns={'id':'port_id'})
    )

    # FIXME: are we computing with ASR?
    pf = ureg('1/(20 tons)')
    if export_destinations is None:
        logger.info("No export destinations provided for Appliance material types; sending exports to nearest port")
        shred_port_mapping=compute_nearest_neighbor_mapping(
            'shred_to_port'
            ,all_shred_inflows[['shred_id','geometry_shred']].to_crs(crs_ll),'geometry_shred',
            caports_use.to_crs(crs_ll),'geometry_port',
            'shred_id',radius=500,max_options=3)

        map_join_key='shred_id'

        table3_shred_port =(
            all_shred_inflows.drop(columns=['geometry_shred', 'distance'])
            .join(shred_port_mapping.set_index(map_join_key),
                on=map_join_key,
                rsuffix='_portx' # FIXME: to avoid conflicts, but should deal with this explicitly
                )
            .assign(
                ferrous_weight=lambda x: x.ferrous + x.white_goods*df_mc2.loc['wg','ferrous'],
                ferrous_trips =lambda x: (x.ferrous_weight * pf).pint.magnitude,
                nonferrous_weight=lambda x: x.nonferrous + x.white_goods*df_mc2.loc['wg','nonferrous'],
                nonferrous_trips =lambda x: (x.nonferrous_weight * pf).pint.magnitude,
                
            )
            .rename(columns={
                'port_id':'d_id',
                'n1_port':'d_n1',
                'n2_port':'d_n2'
                })
        )

    else:
        generated_shredded_metals=(
            all_shred_inflows
            .assign(
                # layer='Appliance', # FIXME: from class?
                # wt_sent=lambda x: x.wt_sent*(1-asr_frac),
                # ttype='shred_to_port', # FIXME: should be shred_to_export
                # material_stream=lambda x: x.material_grouping.map(trip_type_mat_class_map),
                # EMFAC_class='T7 POLA Class 8',
                # trips = lambda x: (x.wt_sent * pf).pint.magnitude, 
                # year=2021, #FIXME: hardcode
                ferrous_weight=lambda x: x.ferrous + x.white_goods*df_mc2.loc['wg','ferrous'],
                ferrous_trips =lambda x: (x.ferrous_weight * pf).pint.magnitude,
                nonferrous_weight=lambda x: x.nonferrous + x.white_goods*df_mc2.loc['wg','nonferrous'],
                nonferrous_trips =lambda x: (x.nonferrous_weight * pf).pint.magnitude                
            )
            # [schema_to_cols(AnnualizedLayeredGroupedFlowIdSchemaWithFlows) + 
            #  ['o_geometry','d_geometry'] # keep geometries for next phase
            #  ]
        )
        export_materials = set([
            m for m in
            export_destinations.material_grouping.unique()
            # if m in generated_shredded_metals.material_grouping.unique()
            if m in ['Ferrous','NonFerrous']
        ])
        logger.info(f"Mapping exports to destinations using provided proportions for {export_materials}")
        # tweak the export fraction into 
        pt=(
            export_destinations[['material_grouping','d_id','proportion']]
            .filt(lambda x: x.material_grouping.isin(export_materials))
            .pivot(index='d_id',columns='material_grouping',values='proportion').fillna(0)
            .reset_index() # brings in d_id
            .clean_names()
            .rename(columns={c.lower():f'{c.lower()}_prop' for c in list(export_materials)})
        )
        table3_shred_port=(
            generated_shredded_metals
            .merge(pt,how='cross')
            .rename(columns={c:f'{c}_out' for c in generated_shredded_metals.filter(regex='ferrous_(weight|trips)').columns})
            .assign(
                ferrous_weight=lambda x: x.ferrous_weight_out * x.ferrous_prop,
                ferrous_trips=lambda x: x.ferrous_trips_out * x.ferrous_prop,
                nonferrous_weight=lambda x: x.nonferrous_weight_out * x.nonferrous_prop,
                nonferrous_trips=lambda x: x.nonferrous_trips_out * x.nonferrous_prop,
                
                d_n1=lambda x:x.d_id,
                d_n2=lambda x:x.d_id,
                )
        )


    return table3_shred_port, all_shred_inflows


