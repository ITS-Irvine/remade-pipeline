def load_appliance_flows_model(
    case_a,
    caports_ent: DataFrame[EndpointSchema],     # port mappings for appliance exports
    matmap,
    data_source='processed_data_appliance',
    refr_case='min', # min or max
    year=2021,
    layer='Appliances'
):
    # Read in appliance flows, from the single table generated by the appliance flow model
    logger.info("Reading Appliance Flows (model)")

    appliance_metals_dir=f'./{case_a}/'
    
    # Read in appliance flows, from the six distinct model tables (as generated by Monica's original model)
    logger.info("Reading Appliance Flows (mon)")

    appliance_metals_dir=f'./{case_a}/'
    # mapping from appliance model port definitions to entity port definitions
    applport_map_df=pd.DataFrame({
        'applport':['Port of Los Angeles & Port of Long Beach', 'Port of Oakland','LONG BEACH','OAKLAND'],
        'worldport':['LONG BEACH','OAKLAND','LONG BEACH','OAKLAND']
    }).join(caports_ent.reset_index().set_index('n1'),on='worldport')

    appflw_s=(
        pd.concat([
            # TABLE 1: collection flows
            # reports from zip_code to CAR, lda and ldt and mdt trips and weight
            pd.read_csv(
                cpath(data_source,f'{appliance_metals_dir}OD_Appliances_Metals_table1.csv')
                )
            .clean_names()
            .assign(ttype='appliance_collection',
                    origin_address=lambda x: x.n2_car,  # set o addr to zip code, which will be picked up in the logic below
                    o_id=lambda x: x.zip_id,
                    d_id=lambda x: x.car_id
                    )
            

            , # TABLE 2: CAR to shredder
            # reports from CAR to shredder (dest should be in RDRS)
            pd.read_csv(
                cpath(data_source,f'{appliance_metals_dir}OD_Appliances_Metals_table2.csv'))
            .clean_names()
            .rename(columns={'trips':'shredder_trips'})
            .assign(
                ttype='car_to_shredder',
                o_id=lambda x: x.car_id,
                d_id=lambda x: x.shred_id,
                shredder_weight=lambda x: x.shredder_trips * 20,
                )

            , # TABLE 2b: CAR to CL1 landfill
            pd.read_csv(
                cpath(data_source,f'{appliance_metals_dir}OD_Appliances_Metals_table2b.csv'),
                )
            .clean_names()
            .rename(columns={'trips_haz':'haz_trips'})
            .assign(
                ttype='car_to_landfill1',
                o_id=lambda x: x.car_id,
                d_id=lambda x: x.cl1lf_id,
                haz_weight=lambda x: x.haz_trips * 20
                )

            , # TABLE 3: 
            pd.read_csv(
                cpath(data_source,f'{appliance_metals_dir}OD_Appliances_Metals_table3.csv'),
                dtype={'zip_code':str,
                    'destination_address':str})
            .clean_names()
            .assign(
                ttype='shredder_to_export',
                ferrous_weight=lambda x: x.ferrous_trips * 20,
                nonferrous_weight=lambda x: x.nonferrous_trips * 20
                )
            # .join(shr_rdrs.set_index('shredder')[['rdrs']].rename(columns={'rdrs':'o_id'}),on='shredder')
            # .join(applport_map_df.set_index('applport')[['id']],on='port')
            .rename(columns={'shred_id':'o_id',
                             'port_id':'d_id'})

            , # TABLE 3b: 
            pd.read_csv(
                cpath(data_source,f'{appliance_metals_dir}OD_Appliances_Metals_table3b.csv'),
                dtype={'zip_code':str,
                    'destination_address':str})
            .clean_names()
            .assign(
                ttype='shredder_to_landfill',
                other_weight=lambda x: x.other_trips * 20
                )
            .rename(columns={'shred_id':'o_id',
                             'rdrs_id_lfc':'d_id'})

            , # TABLE 4: 
            pd.read_csv(
                cpath(data_source,f'{appliance_metals_dir}OD_Appliances_Metals_table4.csv'),
                dtype={'zip_code':str,
                    'destination_address':str,
                    'car':int})
            .clean_names()
            .assign(
                ttype='landfill_to_car',
                o_id=lambda x: x.rdrs_id_landfill,
                d_id=lambda x: x.car_id
                )
            # .rename(columns={'o_id':'rdrs_id_landfill',
            #                  'd_id':'car_id'})
            .rename(columns={'white_goods':'white_goods_weight',
                            'diverted':'white_goods_trips'})

            , # TABLE 5: refrigerants
            gpd.GeoDataFrame(
                # FIXME: directory
                pd.read_csv(cpath('output_appliance','OD_Appliances_Metals_car_to_reclaimer.csv'))
                .assign(
                    ttype='car_to_reclaimer',
                    # o_id=lambda x: x.apply(lambda row: f'CAR{int(row.car):05d}',axis=1),
                    o_id=lambda x: x.car_id,
                    d_id=lambda x: x.recl_id,
                    geometry_recl=lambda x: gpd.GeoSeries.from_wkt(x.geometry_recl),
                    )
                ,geometry='geometry_recl'
            )
            .set_crs(crs_ll)
            .filt(lambda x: x.case==refr_case)
            .rename(columns={
                'trips':'refr_trips',
                'rec_kg':'refr_weight',
                'ship_weight':'refr_ship_weight',
                'model_size':'container_type',
                
                # FIXME: these are legacy requirements for downstream code to
                # determine reclaimer destinations that needs to be revised
                'n1_recl':'destination',
                'n2_recl':'destination_address'
                })
            .assign(
                refr_weight=lambda x: x.refr_weight * kg_to_tonnes, # convert kg to lbs
                ship_weight=lambda x: x.ship_weight_kg * kg_to_tonnes, # assume 50% of weight is shipped
                dest_x=lambda x: x.geometry_recl.x,
                dest_y=lambda x: x.geometry_recl.y,
            )
            [['o_id','d_id',
              'dest_x','dest_y',
              'container_type','ship_containers_int','ship_weight','refr','refr_weight',
              'ttype','emfac_class','refr_trips','case',
                # FIXME: these are legacy requirements for downstream code to
                # determine reclaimer destinations that needs to be revised
              'destination','destination_address'
              ]] 
        ], ignore_index=True)

        # Don't think these are needed
        # .assign(
        #     orig_zip=lambda x: x.origin_address.str.replace(r'^(.*)(\d{5})(-\d{4})?\s*$',r'\2',regex=True),
        #     dest_zip=lambda x: x.destination_address.str.replace(r'^(.*)(\d{5})(-\d{4})?\s*$',r'\2',regex=True)
        # )
        
        # rename columns to match original code
        .rename(
            columns={
                # 'destination_x':'dest_x',
            #         'destination_y':'dest_y',
                    'origin_x':'orig_x',
                    'origin_y':'orig_y'}
        )
    )
    
    assert appflw_s.o_id.notna().all(), "Some rows are missing o_id values, which are required for flow processing. Please check the source data and the o_id assignment logic."
    assert appflw_s.d_id.notna().all(), "Some rows are missing d_id values, which are required for flow processing. Please check the source data and the d_id assignment logic."
    
    return(appflw_s)

