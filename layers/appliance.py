class ApplianceLayer(ModelLayer):
    """Appliance material flow layer for the REMADE pipeline model.

    Models the lifecycle of major household appliances in California,
    from collection at ZIP codes through Certified Appliance Recyclers
    (CARs), shredders, export ports, landfills, and refrigerant
    reclaimers. The layer processes six flow types:

    - **Collection** — ZIP to CAR (LDA/LDT/MDT vehicles)
    - **CAR to shredder** — Processed appliances to metal shredders
    - **CAR to Class 1 landfill** — Hazardous waste to permitted landfills
    - **Shredder to export** — Ferrous/nonferrous metal to ports
    - **Shredder to CTMSR landfill** — Residuals to CTMSR landfills
    - **CAR to reclaimer** — Refrigerant fluids to reclaimer facilities

    Parameters
    ----------
    matmap_file : str
        Path to the material mapping Excel file.
    appliance_case : ApplianceCase
        Case selection for material composition and flow parameters.
    refr_case : RefrCase
        Refrigerant case (``'min'`` or ``'max'``) for reclaimer flows.
    model_year : int
        Census/model year for spatial data.
    geocoder : Geocoder
        Geocoder instance for assigning geometries to endpoints.
    name : str, default 'Appliance'
        Layer name.
    run_model : bool, default False
        If True, re-runs the appliance flow model before loading flows.

    Attributes
    ----------
    appliance_case : ApplianceCase
        Case selection enum value.
    refr_case : RefrCase
        Refrigerant case enum value.
    model_year : int
        Census/model year.
    df_mc2 : pd.DataFrame
        Material composition matrix.
    geocoder : Geocoder
        Geocoder instance.
    appflw : DataFrame or None
        Loaded appliance flows (set by :meth:`get_flows`).
    endpoints : DataFrame or None
        Geocoded endpoint entities (set by :meth:`get_flows`).
    matmap : DataFrame[RDRSMaterialSchema]
        Material mapping table.

    Notes
    -----
    - Initialization calls :meth:`get_flows`, which performs the full
      loading, geocoding, and aggregation pipeline.
    - If ``run_model=True``, :meth:`model_flows` is called first to
      regenerate the flow CSV files from raw data.

    See Also
    --------
    ModelLayer : Abstract base class.
    EwasteLayer : E-waste layer (similar structure).
    """
    @pa.check_types
    def __init__(self, 
                 config: ApplianceModelConfig,
                 geocoder: Geocoder = None,
                 export_proportions_layer: ModelLayer = None
                 ):
        """Initialize the Appliance layer and load all flow data.

        Parameters
        ----------
        config : ApplianceModelConfig
            Configuration object. Relevant fields:

            - ``matmap_file`` — Path to the material mapping Excel file.
            - ``appliance_case`` — Case selection for material composition.
            - ``refr_case`` — Refrigerant case (``'min'`` or ``'max'``).
            - ``model_year`` — Census/model year.
            - ``geocoder`` — Geocoder instance for endpoint geocoding.
            - ``name`` — Layer name (default ``'Appliance'``).
            - ``run_model`` — If True, regenerate flow CSVs before loading.
        export_proportions_layer : ModelLayer, optional
            Layer providing export proportion data.

        Notes
        -----
        - Material composition is loaded from
          ``material_composition_{appliance_case.value}.csv``.
        - If ``config.run_model=True``, :meth:`model_flows` is called
          before :meth:`get_flows`.
        """
        super().__init__(config.name)
        self.appliance_case            = config.case
        self.refr_case                 = config.refr_case
        self.model_year                = config.model_year
        self.unify_geo_file            = config.unify_geo_file # FIXME: shouldn't be in this class
        self.rass_data_file            = config.rass_data_file  
        self.car_data_file             = config.car_data_file  
        self.refr_recovery_file        = config.refr_recovery_file  
        self.refr_gwp_file             = config.refr_gwp_file       
        self.refr_containers_file      = config.refr_containers_file
        self.refr_vehcap_file          = config.refr_vehcap_file    
        self.refr_reclaimer_file       = config.refr_reclaimer_file    

        self.export_proportions_layer  = export_proportions_layer
        self.geocoder                  = geocoder
        
        self.read_material_mappings(config.matmap_file)
